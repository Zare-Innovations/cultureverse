/*
 * Writes PLACEHOLDERS.md: every bracketed placeholder and href="#" in the source, with file:line and
 * what fills it. Usage: npm run placeholders
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const FILES = [];
for (const dir of ['app', 'components', 'lib']) {
  const walk = (d) => { for (const f of fs.readdirSync(d)) { const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (/\.(tsx?|css)$/.test(f)) FILES.push(p); } };
  walk(path.join(ROOT, dir));
}
FILES.push(path.join(ROOT, '.env.example'));

const FILL = [
  [/\[CULTUREBOWL EVENT URL\]/, 'Set `NEXT_PUBLIC_TICKETMASTER_URL` to the Ticketmaster event page. The bracketed URL is only the fallback when the variable is unset.'],
  [/\[ARTIST NAMES PENDING CONFIRMATION\]/, 'No env var. Once the lineup is confirmed in writing, update `HEADLINER` and `SUPPORTING` in `lib/hero.ts` and delete these lines.'],
  [/\[TAYLOR TOWNSEND\]/, 'No env var. Replace with the approved honoree name in `app/iconhonors/page.tsx` and swap the "Portrait pending" circle for the portrait.'],
  [/\[TERMS\]|\[PRIVACY POLICY\]/, 'No env var. Link the words to the Terms and Privacy pages in `components/StayTappedIn.tsx`.'],
  [/\[LEGAL ENTITY\]/, 'No env var. Replace with the legal entity name in `components/Footer.tsx`.'],
  [/\[CONFIRM[^\]]*\]/, 'No env var. Confirm with Miles whether FORWRD Summit and The Culture EXCHNGE are one event, then delete the note in `app/exchnge/page.tsx`.'],
  [/href="#"/, 'No env var. Footer social, Privacy and Terms links in `components/Footer.tsx`; add the URLs when they exist.'],
];

// Code, not copy: index expressions that happen to look like placeholders.
const IGNORE = new Set(['[HONEYPOT]']);

const rows = [];
for (const file of FILES) {
  const rel = path.relative(ROOT, file);
  fs.readFileSync(file, 'utf8').split('\n').forEach((line, i) => {
    const found = new Set();
    for (const m of line.matchAll(/\[[A-Z][A-Z' :,\-]*[A-Z]\]|\[CONFIRM[^\]]*\]/g)) if (!IGNORE.has(m[0])) found.add(m[0]);
    if (/href="#"/.test(line)) found.add('href="#"');
    for (const token of found) {
      const fill = (FILL.find(([re]) => re.test(token)) || [null, 'Review.'])[1];
      const label = token === 'href="#"' ? `\`${token}\` (${(line.match(/>([^<]+)<\/a>/) || [, '?'])[1].trim()})` : `\`${token}\``;
      rows.push([`${rel}:${i + 1}`, label, fill]);
    }
  });
}

const env = [
  ['`NEXT_PUBLIC_TICKETMASTER_URL`', 'Every "Get tickets" / "Tickets" button. Replaces `[CULTUREBOWL EVENT URL]`.'],
  ['`NEXT_PUBLIC_FORM_ENDPOINT`', 'Receives the Tap In, EXCHNGE, Big Give and ICON HONORS forms as JSON. Replaces the artboards\' `[SQUARESPACE FORM DESTINATION]`, which is not rendered. Unset: the forms show their error line.'],
  ['`NEXT_PUBLIC_SHOP_URL`', 'Shop links. Defaults to https://www.allthingsculturebowl.com/shop.'],
  ['`NEXT_PUBLIC_HEADLINER_ANNOUNCED`', '`true` switches the desktop Home hero to the announced variant.'],
  ['`NEXT_PUBLIC_EXPO_TICKETS_ON_SALE`', '`true` once CultureExpo tickets go on sale: the Expo page swaps "Notify me" for "Get weekend tickets" and adds ticket offers to its Event schema.'],
  ['`NEXT_PUBLIC_GA_ID`', 'GA4 measurement ID. Empty ships no analytics.'],
];

const md = [
  '# Placeholders to fill before launch',
  '',
  'Generated by `npm run placeholders`. Line numbers refer to the current source.',
  '',
  '## Environment variables',
  '',
  '| Variable | Fills |',
  '|---|---|',
  ...env.map(([k, v]) => `| ${k} | ${v} |`),
  '',
  '## In the source',
  '',
  '| File:line | Placeholder | What fills it |',
  '|---|---|---|',
  ...rows.map((r) => `| \`${r[0]}\` | ${r[1]} | ${r[2]} |`),
  '',
  `${rows.length} occurrences.`,
  '',
];
fs.writeFileSync(path.join(ROOT, 'PLACEHOLDERS.md'), md.join('\n'));
console.log(`PLACEHOLDERS.md written: ${rows.length} occurrences.`);
